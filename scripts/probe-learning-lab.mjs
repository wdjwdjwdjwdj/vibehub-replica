import { chromium } from 'playwright';

const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(String(error)));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
await page.goto('http://127.0.0.1:5174/en/vibehub-skill/lab', { waitUntil: 'networkidle', timeout: 60000 });
const report = { route: page.url(), errors };
report.initial = await page.locator('.learning-product').getAttribute('class');
await page.locator('.learning-option-cards button').nth(1).click();
report.optionB = await page.locator('.learning-product').getAttribute('class');
await page.locator('.learning-choose').click();
report.afterChoose = { stage: await page.locator('.learning-route li.is-current').innerText(), priorityCount: await page.locator('.learning-priority-options button').count() };
await page.locator('.learning-priority-options button').nth(1).click();
report.afterPriority = { priority: await page.locator('.learning-product').locator('.learning-preview-caption b').innerText(), stage: await page.locator('.learning-route li.is-current').innerText() };
const sliders = page.locator('.learning-control input');
await sliders.nth(0).fill('82');
await sliders.nth(1).fill('58');
await sliders.nth(2).fill('70');
report.sliderValues = await sliders.evaluateAll((items) => items.map((item) => item.value));
await page.locator('.learning-next').click();
for (const check of await page.locator('.learning-checks button').all()) await check.click();
report.checks = await page.locator('.learning-checks button.is-checked').count();
await page.locator('.learning-finish').click();
report.completed = await page.locator('.learning-complete').count();
await page.locator('.learning-copy-exercise').click();
await page.waitForTimeout(100);
report.copyLabel = await page.locator('.learning-copy-exercise').innerText();
report.errors = errors;
console.log(JSON.stringify(report, null, 2));
await context.close();
await browser.close();
if (errors.length || report.completed !== 1 || report.checks !== 3 || !/copied/i.test(report.copyLabel)) process.exit(1);
